"""Render a Docker host's services into a compose file.

Input is the validated DockerService list (see schemas.py), so the output can
only contain images, published ports, named volumes and plain settings.
`secret:<name>` values become ${STACKSECRET_<NAME>} references; the host
generates those values itself (infra/ansible/roles/docker_services).
"""

from __future__ import annotations

import yaml


def secret_var(name: str) -> str:
    return f"STACKSECRET_{name.upper()}"


def render(services: list[dict]) -> tuple[str, list[str]]:
    """(compose.yaml text, secret variable names)."""
    secrets: set[str] = set()
    out: dict = {"services": {}, "volumes": {}}
    for svc in services:
        env = {}
        for k, v in (svc.get("env") or {}).items():
            if v.startswith("secret:"):
                var = secret_var(v.split(":", 1)[1])
                secrets.add(var)
                env[k] = "${" + var + "}"
            else:
                env[k] = v
        entry: dict = {"image": svc["image"], "container_name": svc["name"], "restart": "unless-stopped",
                       "security_opt": ["no-new-privileges:true"]}
        if svc.get("ports"):
            entry["ports"] = list(svc["ports"])
        if env:
            entry["environment"] = env
        if svc.get("volumes"):
            entry["volumes"] = list(svc["volumes"])
            for vol in svc["volumes"]:
                out["volumes"][vol.split(":", 1)[0]] = {}
        out["services"][svc["name"]] = entry
    if not out["volumes"]:
        del out["volumes"]
    text = "# Generated by proxmox-ai-infra-demo. Edit the stack in the console, not this file.\n"
    return text + yaml.safe_dump(out, sort_keys=False), sorted(secrets)
